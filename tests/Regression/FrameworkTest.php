<?php

namespace Tests\Regression;

use App\Library\Helper;
use Illuminate\Support\Facades\Route;
use Illuminate\Support\Facades\Storage;
use PHPUnit\Framework\Attributes\DataProvider;

class FrameworkTest extends RegressionTestCase
{
    public function testEveryRegisteredControllerActionExists(): void
    {
        $count = 0;
        foreach (Route::getRoutes() as $route) {
            $action = $route->getActionName();
            if (!str_contains($action, '@')) continue;
            [$class, $method] = explode('@', $action, 2);
            $this->assertTrue(class_exists($class), $route->uri() . ': ' . $class);
            $this->assertTrue(method_exists($class, $method), $route->uri() . ': ' . $action);
            $count++;
        }
        $this->assertGreaterThan(80, $count);
    }

    public static function pages(): array
    {
        return array_map(fn ($path) => [$path], ['/', '/admin', '/admin/product/list']);
    }

    #[DataProvider('pages')]
    public function testPublicPagesRender(string $path): void
    {
        $this->get($path)->assertOk();
    }

    public function testLegacyShopShortcutRedirects(): void
    {
        $this->get('/s')->assertRedirect('http://localhost?theme=Material#/record?tab=');
    }

    public function testAllProtectedRoutesRejectAnonymousRequests(): void
    {
        $count = 0;
        foreach (Route::getRoutes() as $route) {
            if (!in_array('auth.token', $route->gatherMiddleware(), true)) continue;
            $uri = preg_replace('/\{[^}]+\}/', '1', $route->uri());
            $response = $this->api($route->methods()[0], '/' . $uri);
            $this->assertSame(401, $response->status(), $route->uri() . ': ' . $response->getContent());
            $count++;
        }
        $this->assertGreaterThan(50, $count);
    }

    public function testChineseValidationAndNotFoundResponses(): void
    {
        $this->api('POST', '/api/admin/auth/login')->assertStatus(422)->assertJsonValidationErrors(['email', 'password']);
        $response = $this->get('/does-not-exist', ['Accept' => 'application/json', 'X-Requested-With' => 'XMLHttpRequest']);
        $response->assertNotFound();
        $this->assertStringNotContainsString('exception.not_found', $response->getContent());
    }

    public function testDateSerializationRetainsExistingFrontendFormat(): void
    {
        $this->merchant->created_at = '2020-01-02 03:04:05';
        $this->product->created_at = '2020-01-02 03:04:05';
        $this->assertSame('2020-01-02 03:04:05', $this->merchant->toArray()['created_at']);
        $this->assertSame('2020-01-02 03:04:05', $this->product->toArray()['created_at']);
    }

    public function testExistingShortLinksRoundTrip(): void
    {
        foreach ([1, 2, 10, 999999, 2147483647] as $id) {
            foreach ([Helper::ID_TYPE_USER, Helper::ID_TYPE_PRODUCT, Helper::ID_TYPE_CATEGORY] as $type) {
                $this->assertSame($id, Helper::id_decode(Helper::id_encode($id, $type), $type));
            }
        }
    }

