    public function testCloudDisksRetainExistingConfigurationAndUrls(): void
    {
        config(['filesystems.disks.oss.access_id' => 'test-id', 'filesystems.disks.oss.access_key' => 'test-secret',
            'filesystems.disks.oss.endpoint' => 'oss-cn-hangzhou.aliyuncs.com', 'filesystems.disks.oss.bucket' => 'test-bucket',
            'filesystems.disks.oss.cdnDomain' => 'cdn.example.test', 'filesystems.disks.oss.ssl' => true,
            'filesystems.disks.qiniu.access_key' => 'test-id', 'filesystems.disks.qiniu.secret_key' => 'test-secret',
            'filesystems.disks.qiniu.bucket' => 'test-bucket', 'filesystems.disks.qiniu.domains.default' => 'cdn.example.test',
            'filesystems.disks.s3.key' => 'test-id', 'filesystems.disks.s3.secret' => 'test-secret',
            'filesystems.disks.s3.region' => 'us-east-1', 'filesystems.disks.s3.bucket' => 'test-bucket']);
        $this->assertSame('https://cdn.example.test/images/test.png', Storage::disk('oss')->url('images/test.png'));
        $this->assertStringContainsString('cdn.example.test/images/test.png', Storage::disk('qiniu')->url('images/test.png'));
        $this->assertStringContainsString('test-bucket.s3', Storage::disk('s3')->url('images/test.png'));
    }
